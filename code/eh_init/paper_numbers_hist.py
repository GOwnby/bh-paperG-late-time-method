#!/usr/bin/env python3
"""Numbers of Sec. 3 of main.tex that come from the older logs of the event-horizon-regular runs (static validation, local mass check, collapse location, truncation-error
mass, mu_v identity, uniform-U grid).  Parses results_eh_init.txt, results_tailonly_collapse.txt, results_aniso_noise.txt, results_seeded_identity_constraint.txt,
results_checks_extra.txt (shipped, or regenerated by `verify.sh --full`) and prints 'VALUE <name> <number>' lines; output: results_paper_numbers_hist.txt."""
import os, re
here = os.path.dirname(os.path.abspath(__file__))
OUT = []
def val(name, x, fmt='%.6g'):
    s = 'VALUE %s %s' % (name, fmt % x); OUT.append(s); print(s)
def lines(fn): return open(os.path.join(here, fn)).read().splitlines()
f = lambda s: float(s)

# static validation: sigma_v error at U ~ 1, v = 100 for h = 0.2, 0.1, 0.05
L = lines('results_eh_init.txt'); cur = None
for l in L:
    m = re.match(r'h (\S+) \S+ nu', l)
    if m: cur = m.group(1)
    elif cur and l.strip().startswith('v=100'):
        m = re.search(r'U=(?:0\.996|1) dsig=\S+ dsV=(\S+)', l); val('static_dsV_U1_v100_h%s' % cur, abs(f(m.group(1))), '%.1e')
        if cur == '0.05': cur = None
# B = 0.04 two-grid Richardson value of |sigma_v| (U = 0.3, v = 95)
i = next(j for j, l in enumerate(L) if l.startswith('== B=0.04'))
sv = [f(re.search(r'U=0\.3\s+v=50.*?\| v=95 sV=(\S+)', L[j]).group(1)) for j in range(i, i + 6) if re.match(r'\s+U=0\.3\s+v=50', L[j])]
val('B0.04_sigma_v_h0.05', abs(sv[0]), '%.5f'); val('B0.04_sigma_v_h0.025', abs(sv[1]), '%.5f'); val('B0.04_richardson', abs(sv[1]) + (abs(sv[1]) - abs(sv[0]))/3, '%.5f')
val('B0.04_kappa_mu_f', f(re.search(r'kappa-\(mu_f\)=(\S+)', L[i + 1]).group(1)), '%.6f')
# local mass check (B = 0.03, k = 3/2, h = 0.025)
i = next(j for j, l in enumerate(L) if l.startswith('B=0.03 k=1.5 h=0.025'))
muf = f(re.search(r'mu_f=(\S+)', L[i]).group(1)); kf = f(re.search(r'kappa-\(mu_f\)=(\S+)', L[i]).group(1))
rows = {}
for l in L[i + 1:i + 12]:
    m = re.match(r'\s+U=(\S+) v=(\d+)\s+mu=(\S+)\s+kappa-\(mu_loc\)=(\S+)', l)
    if m: rows[(m.group(1), int(m.group(2)))] = (f(m.group(3)), f(m.group(4)))
r1 = [abs(rows[('0.1', v)][0]/muf - 1) for v in (40, 50, 55, 60, 65)]
r3 = [abs(rows[('0.3', v)][0]/muf - 1)*100 for v in (40, 50, 55, 60, 65)]
val('muloc_U0.1_rel_min', min(r1), '%.1e'); val('muloc_U0.1_rel_max', max(r1), '%.1e'); val('muloc_U0.3_percent_min', min(r3), '%.2f'); val('muloc_U0.3_percent_max', max(r3), '%.2f')
val('muloc_U0.1_v40', rows[('0.1', 40)][0], '%.5e'); val('muloc_mu_f', muf, '%.5e')
val('muloc_kappa_shift_max', max(abs(rows[k][1] - kf) for k in rows if k[0] in ('0.1', '0.3')), '%.1e')
# collapse location
L = lines('results_tailonly_collapse.txt'); i = next(j for j, l in enumerate(L) if l.startswith('== first NaN column'))
for B in ('0.03', '0.04', '0.05'):
    j = next(j for j in range(i, len(L)) if L[j] == 'B=' + B)
    val('Uc_B%s' % B, f(re.search(r'U=(\S+)', L[j + 1]).group(1)), '%.3f'); val('Uc_vfirstnan_B%s' % B, f(re.search(r'at v=(\S+)', L[j + 2]).group(1)), '%.2f')
# truncation-error mass of the static solution
L = lines('results_aniso_noise.txt'); q = []
for l in L:
    m = re.match(r'hs=(\S+) hv=(\S+)\s+mu\(U=0\.3,v=40\)=(\S+)', l)
    if m: q.append(f(m.group(3))/(f(m.group(1))**2 + f(m.group(2))**2)); 
val('aniso_ratio_min', min(q), '%.2e'); val('aniso_ratio_max', max(q), '%.2e'); val('aniso_ratio_hs0.1_hv0.025', q[3], '%.2e'); val('aniso_ratio_hs0.025_hv0.1', q[4], '%.2e')
# mu_v identity (seeded data)
L = lines('results_seeded_identity_constraint.txt'); blocks = {}
cur = None
for l in L:
    m = re.match(r'h (\S+)$', l)
    if m: cur = m.group(1); continue
    m = re.match(r'\s+U=(\S+) v=(\d+)\s+dmu/dv=\S+\s+rhs=\S+\s+ratio=(\S+)', l)
    if m and cur: blocks[(cur, m.group(1), int(m.group(2)))] = f(m.group(3))
val('muid_U0.5_v5_h0.05', blocks[('0.05', '0.50', 5)], '%.4f'); val('muid_U0.5_v5_h0.025', blocks[('0.025', '0.50', 5)], '%.4f')
val('muid_U1_v30_h0.05', blocks[('0.05', '1.00', 30)], '%.4f'); val('muid_U1_v30_h0.025', blocks[('0.025', '1.00', 30)], '%.4f')
# uniform-U grid
L = lines('results_checks_extra.txt')
for l in L:
    m = re.match(r'uniform U grid h_U=(\S+) h_v=\S+: first NaN row at v=(\S+)', l)
    if m: val('uniform_nan_v_hU%s' % m.group(1), f(m.group(2)), '%.1f')
open(os.path.join(here, 'results_paper_numbers_hist.txt'), 'w').write('\n'.join(OUT) + '\n')
